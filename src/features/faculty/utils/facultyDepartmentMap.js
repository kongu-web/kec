/**
 * Normalise slug alias or alternate names
 */
export const normaliseDeptSlug = (rawSlug) => {
  if (!rawSlug) return 'cse';
  const clean = String(rawSlug).toLowerCase().trim();
  if (clean === 'automobile') return 'auto';
  if (clean === 'chem') return 'chemical';
  if (clean === 'barch' || clean === 'b.arch') return 'architecture';
  return clean;
};

/**
 * Get department metadata by slug
 */
export const getDepartmentBySlug = (slug) => {
  const norm = normaliseDeptSlug(slug);
  return DEPARTMENT_MAP[norm] || {
    slug: norm,
    linwaysCode: norm.toUpperCase(),
    name: norm.toUpperCase(),
    shortName: norm.toUpperCase(),
    category: 'Department',
    csvFile: `${norm}.csv`,
    imageFolder: norm,
    pdfFile: ''
  };
};

/**
 * Get department slug by Linways code
 */
export const getSlugByLinwaysCode = (code) => {
  if (!code) return '';
  const upper = String(code).toUpperCase().trim();
  const entry = Object.values(DEPARTMENT_MAP).find(
    (dept) => dept.linwaysCode.toUpperCase() === upper
  );
  return entry ? entry.slug : upper.toLowerCase();
};

/**
 * Get Linways code by department slug
 */
export const getLinwaysCodeBySlug = (slug) => {
  const dept = getDepartmentBySlug(slug);
  return dept.linwaysCode;
};
